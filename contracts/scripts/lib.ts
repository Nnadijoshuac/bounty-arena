import { ethers } from "hardhat";
import * as fs from "fs";
import * as path from "path";
import { exportAbi } from "./export-abi";

export const ROOT = path.join(__dirname, "../..");
export const WEB_PUBLIC = path.join(ROOT, "web/public");

export type DeployArgs = {
  key: "local" | "arcTestnet" | "arcMainnet";
  usdc: string;
  treasury: string;
  arbiter: string;
  verifier: string;
};

/** Deploys the arena and its text store, then writes every file the web app, SDK and verifier read. */
export async function deployArena(args: DeployArgs) {
  const [deployer] = await ethers.getSigners();
  const { chainId } = await ethers.provider.getNetwork();

  const arena = await ethers.deployContract("BountyArena", [args.usdc, args.treasury, args.arbiter, args.verifier]);
  await arena.waitForDeployment();
  const store = await ethers.deployContract("ArenaTextStore");
  await store.waitForDeployment();
  const arenaAddress = await arena.getAddress();
  const storeAddress = await store.getAddress();
  const startBlock = await ethers.provider.getBlockNumber();

  const deployment = {
    network: args.key,
    chainId: Number(chainId),
    arena: arenaAddress,
    textStore: storeAddress,
    usdc: args.usdc,
    treasury: args.treasury,
    arbiter: args.arbiter,
    verifier: args.verifier,
    deployer: deployer.address,
    startBlock,
    deployedAt: new Date().toISOString(),
    timeOffset: 0,
  };

  // web/public/deployments/<key>.json is what the web app, SDK and verifier read at runtime
  const outDir = path.join(WEB_PUBLIC, "deployments");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, `${args.key}.json`), JSON.stringify(deployment, null, 2) + "\n");

  // keep the machine-readable manifest in step
  const manifestPath = path.join(WEB_PUBLIC, "arena.json");
  if (fs.existsSync(manifestPath)) {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    manifest.networks = manifest.networks || {};
    manifest.networks[args.key] = {
      ...(manifest.networks[args.key] || {}),
      chainId: Number(chainId),
      arena: arenaAddress,
      textStore: storeAddress,
      usdc: args.usdc,
      arbiter: args.arbiter,
      verifier: args.verifier,
      startBlock,
    };
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  }

  writeSharedAddresses(Number(chainId), {
    arena: arenaAddress,
    textStore: storeAddress,
    usdc: args.usdc,
    arbiter: args.arbiter,
    verifier: args.verifier,
    startBlock,
  });

  await exportAbi();
  return deployment;
}

/** Typed addresses for the new frontend: shared/src/addresses.generated.ts, one entry per chain. */
function writeSharedAddresses(chainId: number, entry: Record<string, string | number>) {
  const file = path.join(ROOT, "shared/src/addresses.generated.ts");
  let current: Record<string, unknown> = { "31337": null, "5042002": null, "5042": null };
  if (fs.existsSync(file)) {
    const txt = fs.readFileSync(file, "utf8");
    const start = txt.lastIndexOf("= {");
    if (start > 0) current = { ...current, ...JSON.parse(txt.slice(start + 2, txt.lastIndexOf("}") + 1)) };
  }
  current[String(chainId)] = entry;
  const body = [
    "// Generated by contracts/scripts/lib.ts on deploy. Do not edit by hand.",
    'import type { Address } from "viem";',
    "",
    "type Entry = { arena: Address; textStore: Address; usdc: Address; arbiter: Address; verifier: Address; startBlock: number } | null;",
    "",
    `export const GENERATED: { 31337: Entry; 5042002: Entry; 5042: Entry } = ${JSON.stringify(current, null, 2)};`,
    "",
  ].join("\n");
  fs.writeFileSync(file, body);
}
